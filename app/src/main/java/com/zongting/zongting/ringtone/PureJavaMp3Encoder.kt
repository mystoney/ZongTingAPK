                if (bits == 8) {
                    bytes.write(cur)
                    cur = 0; bits = 0
                }
                val t = minOf(n, 8 - bits)
                cur = (cur shl t) or ((v shr (n - t)) and ((1 shl t) - 1))
                bits += t; n -= t; v = v and ((1 shl n) - 1)
            }
        }

        fun toByteArray(): ByteArray {
            if (bits > 0) {
                cur = cur shl (8 - bits)
                bytes.write(cur)
            }
            return bytes.toByteArray()
        }
    }

    // ── MP3 frame header ──────────────────────────────────────────────────
    // MPEG-1, Layer III, no CRC, 192kbps, 44100Hz, no padding, stereo
    private val mp3Header = byteArrayOf(
        0xFF.toByte(), 0xFB.toByte(), 0x90.toByte(), 0x00.toByte()
    )

    // ── Encode one MP3 frame ──────────────────────────────────────────────
    private fun encodeFrame(samplesL: ShortArray, samplesR: ShortArray): ByteArray {
        val frameSize = BYTES_PER_FRAME

        // 1. Build 36-sample overlapping input from 32 subband filter output
        //    For simplicity, use the first 36 samples (zero-pad if needed)
        val inputL = DoubleArray(36) { i ->
            if (i < samplesL.size) samplesL[i].toDouble() / 32768.0 else 0.0
        }
        val inputR = DoubleArray(36) { i ->
            if (i < samplesR.size) samplesR[i].toDouble() / 32768.0 else 0.0
        }

        // 2. Apply window and MDCT → 18 spectral lines
        val windowedL = DoubleArray(36) { i -> inputL[i] * mdctWindow[i] }
        val windowedR = DoubleArray(36) { i -> inputR[i] * mdctWindow[i] }
        val specL = mdct(windowedL)
        val specR = mdct(windowedR)

        // 3. Joint stereo: compute mid (L+R)/2 and side (L-R)/2
        val specM = DoubleArray(specL.size) { i -> (specL[i] + specR[i]) / 2.0 }
        val specS = DoubleArray(specR.size) { i -> (specL[i] - specR[i]) / 2.0 }

        // 4. Quantize spectral lines
        //    For each spectral line: quantize = sign * floor(|x|^0.75 / stepsize)
        val globalGain = 210  // quantization step
        val quantStep = 2.0.pow((255 - globalGain) / 4.0) * 32768.0

        val quantL = IntArray(specL.size)
        val quantS = IntArray(specS.size)
        for (i in specL.indices) {
            val ml = abs(specM[i])
            val sl = abs(specS[i])
            val qL = min((ml / quantStep).toInt(), 8191)
            val qS = min((sl / quantStep).toInt(), 8191)
            quantL[i] = qL
            quantS[i] = qS
        }

        // 5. Write MP3 frame
        val bw = BitWriter()

        // 5a. Side info (for short blocks - simplified)
        bw.write(0, 9)       // main_data_begin
        bw.write(0, 1)       // private_bit
        bw.write(0, 1)       // scfsi (channel 2)

        // 5b. Scale factor selection
        for (ch in 0 until 2) {
            bw.write(0, 1)    // scfsi_band
            bw.write(0, 1)
            bw.write(0, 1)
            bw.write(0, 1)
        }

        // 5c. Granule (only 1 granule for simplicity)
        // Part 2
        bw.write(globalGain, 8)   // global_gain
        bw.write(0, 6)             // slen1 + slen2 (scale factors)
        bw.write(0, 1)             // block_type flag
        bw.write(0, 1)             // mixed block flag
        bw.write(0, 4)             // table select (0 = quiet table)
        bw.write(0, 3)             // region0 count
        bw.write(0, 8)             // preflag + quantStep + scalefac_scale + count1table

        // 5d. Scale factors (all zero for simplicity - quant=0)
        // No scale factors written since all quantized values are 0

        // 5e. Encoded spectral data - write quantized values as fixed-width
        // Use 12 bits per value (linbits approach)
        for (i in quantL.indices) {
            val vL = quantL[i]
            val vS = quantS[i]
            // Write vL (up to 13 bits for linbits) then vS (up to 13 bits)
            if (vL > 0) { bw.write(0x2000 or vL, 14) } else { bw.write(0, 1) }
            if (vS > 0) { bw.write(0x2000 or vS, 14) } else { bw.write(0, 1) }
        }

        val mainData = bw.toByteArray()

        // 6. Assemble frame: header + ancillary data + main_data
        val frame = ByteArray(4 + maxOf(mainData.size, frameSize - 4))
        mp3Header.copyInto(frame, 0, 0, 4)
        mainData.copyInto(frame, 4, 0, mainData.size)

        // Pad the rest with 0
        return frame.copyOf(frameSize.coerceAtLeast(4 + mainData.size))
    }

    // ── Main encode function ──────────────────────────────────────────────
    /**
     * Encode interleaved 16-bit stereo PCM bytes to MP3.
     * @param pcmBytes interleaved L/R 16-bit signed samples (little-endian)
     * @param sampleRate sample rate (only 44100 supported)
     * @param bitrateKbps bitrate in kbps
     * @return MP3 bytes with ID3v2 header
     */
    fun encode(
        pcmBytes: ByteArray,
        sampleRate: Int = SAMPLE_RATE,
        bitrateKbps: Int = BITRATE_KBPS
    ): ByteArray {
        Log.d(TAG, "Encoding ${pcmBytes.size} bytes PCM → MP3 (${bitrateKbps}kbps)")

        // Convert PCM bytes to short arrays
        val stereoSamples = pcmBytes.size / 4
        val samplesL = ShortArray(stereoSamples)
        val samplesR = ShortArray(stereoSamples)

        for (i in 0 until stereoSamples) {
            val li = i * 4
            val ri = li + 2
            if (li + 1 < pcmBytes.size && ri + 1 < pcmBytes.size) {
                samplesL[i] = ((pcmBytes[li + 1].toInt() shl 8) or (pcmBytes[li].toInt() and 0xFF)).toShort()
                samplesR[i] = ((pcmBytes[ri + 1].toInt() shl 8) or (pcmBytes[ri].toInt() and 0xFF)).toShort()
            }
        }

        val output = ByteArrayOutputStream()

        // Write ID3v2.3 header
        output.writeBytes(id3v2Header("ZongTing", "Audio", 0))

        // Encode in frames of 1152 stereo samples
        var offset = 0
        var frameCount = 0
        while (offset + 1152 <= samplesL.size) {
            val frameL = ShortArray(1152)
            val frameR = ShortArray(1152)
            for (i in 0 until 1152) {
                frameL[i] = samplesL[offset + i]
                frameR[i] = samplesR[offset + i]
            }
            val mp3Frame = encodeFrame(frameL, frameR)
            output.writeBytes(mp3Frame)
            offset += 1152
            frameCount++
        }

        // Write zero padding frames if needed
        while (offset < samplesL.size) {
            val remaining = minOf(1152, samplesL.size - offset)
            val frameL = ShortArray(1152)
            val frameR = ShortArray(1152)
            for (i in 0 until remaining) {
                frameL[i] = samplesL[offset + i]
                frameR[i] = samplesR[offset + i]
            }
            // Zero-pad the rest
            val mp3Frame = encodeFrame(frameL, frameR)
            output.writeBytes(mp3Frame)
            offset += 1152
        }

        // Write ID3v1
        output.writeBytes(id3v1Tag("ZongTing", "Audio", "ZongTing"))

        val result = output.toByteArray()
        Log.d(TAG, "Encoded $frameCount MP3 frames, total ${result.size} bytes")
        return result
    }

    private fun id3v2Header(title: String, artist: String, year: Int): ByteArray {
        val tagBytes = "$title - $artist".toByteArray(Charsets.UTF_8)
        val size = 10 + tagBytes.size + 128  // header + content + ID3v1
        return byteArrayOf(
            'I'.code.toByte(), 'D'.code.toByte(), '3'.code.toByte(),
            3, 0, 0,  // v2.3
            0,  // flags
            (size shr 21 and 0x7F).toByte(),
            (size shr 14 and 0x7F).toByte(),
            (size shr 7 and 0x7F).toByte(),
            (size and 0x7F).toByte()
        )
    }

    private fun id3v1Tag(title: String, artist: String, album: String): ByteArray {
        val tag = ByteArray(128)
        "TAG".toByteArray().copyInto(tag, 0, 0, 3)
        title.toByteArray(Charsets.ISO_8859_1).copyInto(tag, 3, 0, minOf(title.length, 30))
        artist.toByteArray(Charsets.ISO_8859_1).copyInto(tag, 33, 0, minOf(artist.length, 30))
        album.toByteArray(Charsets.ISO_8859_1).copyInto(tag, 63, 0, minOf(album.length, 30))
        tag[125] = 0  // genre = Other
        return tag
    }
