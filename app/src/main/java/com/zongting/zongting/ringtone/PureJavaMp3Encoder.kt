    // ── MDCT ──────────────────────────────────────────────────────────────
    // MDCT size 18 (for 36 input samples after windowing)
    private val mdctWindow = DoubleArray(36) { i ->
        sin(PI * (i + 0.5) / 36.0)
    }

    private fun mdct(input: DoubleArray): DoubleArray {
        val n = input.size
        val halfN = n / 2
        val output = DoubleArray(halfN)
        for (k in 0 until halfN) {
            var sum = 0.0
            for (j in 0 until n) {
                sum += input[j] * cos(PI / n * (j + 0.5 + halfN) * (2 * k + 1))
            }
            output[k] = sum * sqrt(2.0 / n)
        }
        return output
    }

